"""
Generate Art/Models/MODELS.md from the build/verify logs in Art/Models/_logs.
Run with any Python 3: python Tools/blender/write_models_md.py
"""
import json
import os
import datetime

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
LOGS = os.path.join(REPO, "Art", "Models", "_logs")
MODELS = os.path.join(REPO, "Game", "Assets", "Resources", "Models")
OUT = os.path.join(REPO, "Art", "Models", "MODELS.md")

# Per-asset notes (front direction is the Unity local axis the asset's front faces).
META = json.load(open(os.path.join(HERE, "models_meta.json"), encoding="utf-8"))

ORDER = [
    "Glasses_Open", "Glasses_Folded", "GlassesCase", "Passport_Open", "Passport_Closed",
    "Passenger_Parts", "Controller_Left", "Controller_Right",
    "Sofa", "DiningTable", "DiningChair", "KitchenRun", "Fridge", "BathroomSink", "Door", "Suitcase", "Phone",
    "VintageCamera", "Noisemaker", "HandLantern", "GardenLamp", "Reflector", "VerificationDesk", "VoidStamp",
    "FestivalToken", "OpticalPanel",
    "Landmark_Eiffel", "Landmark_Liberty", "Landmark_Pagoda", "Landmark_ArchTower", "Landmark_DomedPavilion",
    "Landmark_ClockTower", "Landmark_ColumnGate", "StreetLamp_Paris", "Saeed",
]


def load(name, kind):
    p = os.path.join(LOGS, "%s.%s.json" % (name, kind))
    if os.path.exists(p):
        with open(p, encoding="utf-8") as fh:
            return json.load(fh)
    return None


def fmt_dims(d):
    # Blender X (width), Y (depth), Z (height)
    return "%.3f x %.3f x %.3f" % (d[0], d[1], d[2])


def main():
    rows = []
    details = []
    missing = []
    for name in ORDER:
        fbx = os.path.join(MODELS, name + ".fbx")
        b = load(name, "build")
        v = load(name, "verify")
        m = META.get(name, {})
        if not os.path.exists(fbx) or b is None:
            missing.append(name)
            continue
        src = v or b
        children = [o["name"] for o in src["objects"] if o.get("parent")]
        kb = os.path.getsize(fbx) / 1024.0
        verified = "yes" if v else "no"
        prev = name + ".png" if os.path.exists(os.path.join(REPO, "Art", "Models", name + ".png")) else "-"
        rows.append("| `%s.fbx` | %d | %.0f KB | %s | %s | %s | %s | %s | %s |" % (
            name, src["tris"], kb, fmt_dims(src["dims_m"]), ", ".join("`%s`" % c for c in children),
            ", ".join(src["slots"]), m.get("front", "+Z"), m.get("source", "Modelled (Blender script)"),
            "`%s`" % prev if prev != "-" else "-"))
        det = ["### %s.fbx" % name, ""]
        det.append("- Script: `Tools/blender/%s`" % m.get("script", "?"))
        det.append("- Re-import check: %s%s" % (verified, (" (Blender FBX importer; names/slots/dims below are from the re-import)" if v else "")))
        if m.get("origin"):
            det.append("- Origin: %s" % m["origin"])
        det.append("- Front (Unity local): %s" % m.get("front", "+Z"))
        if v:
            issues = []
            for o in v["objects"]:
                if o["type"] != "MESH":
                    continue
                if o.get("loose_verts") or o.get("loose_edges"):
                    issues.append("%s loose geometry" % o["name"])
                if o.get("signed_volume", 0) < 0 and not o.get("boundary_edges"):
                    issues.append("%s negative volume (inverted normals?)" % o["name"])
                if o.get("degenerate_faces"):
                    issues.append("%s %d degenerate faces" % (o["name"], o["degenerate_faces"]))
            det.append("- Mesh checks: %s" % ("clean (no loose geometry, closed shells have outward normals)" if not issues else "; ".join(issues)))
        det.append("")
        det.append("| Object | Parent | Tris | Slots | Size W x D x H (m) |")
        det.append("|---|---|---|---|---|")
        for o in src["objects"]:
            det.append("| `%s` | %s | %s | %s | %s |" % (
                o["name"], o.get("parent") or "-", o.get("tris", "-"),
                ", ".join(o.get("slots", []) or []) or "-",
                fmt_dims(o["world_dims"]) if o.get("world_dims") else "-"))
        if m.get("notes"):
            det.append("")
            for n in m["notes"]:
                det.append("- " + n)
        det.append("")
        details.append("\n".join(det))

    lines = []
    lines.append("# The Twelfth Stamp: model list")
    lines.append("")
    lines.append("Generated by `Tools/blender/write_models_md.py` from the build and re-import logs in `Art/Models/_logs/` "
                 "(last run %s). Every model is built by a Python script in `Tools/blender/`; run it headless with "
                 "`blender -b --factory-startup --python Tools/blender/<script>.py` to rebuild." % datetime.date.today().isoformat())
    lines.append("")
    lines.append("## Conventions (all files)")
    lines.append("")
    lines.append("- Output: `Game/Assets/Resources/Models/<Name>.fbx`, one asset per file. Units are metres at real-world scale. "
                 "The FBX stores UnitScaleFactor 100 (1 unit = 1 m), so Unity imports at scale 1.")
    lines.append("- Export call: `export_scene.fbx(use_selection=True, apply_unit_scale=True, apply_scale_options='FBX_SCALE_ALL', "
                 "axis_forward='-Z', axis_up='Y', bake_space_transform=True, object_types={'MESH','EMPTY'}, mesh_smooth_type='FACE', "
                 "use_tspace=True, add_leaf_bones=False, bake_anim=False)`.")
    lines.append("- Orientation: assets are built with their front facing Blender -Y and up +Z. In the exported FBX that front is +Z "
                 "(verified by parsing the raw file). Unity mirrors X on import, so **the front faces Unity local +Z "
                 "(transform.forward)**, up is +Y, and Blender +X becomes Unity -X. The \"Front\" column gives each file's front axis.")
    lines.append("- Hierarchy: each file has one root empty named after the file. Every mesh is a child of that root. "
                 "Rotation and scale are applied on every object (identity), and child locations are the pivots listed below.")
    lines.append("- Materials: slots are named from the TS_* list. Base colours are preview values only; the game assigns its own materials by slot name. "
                 "All meshes have UVs: smart-project by default, with explicit 0..1 UVs where noted. "
                 "Meshes have custom (weighted) normals and are triangulated where they had n-gons.")
    lines.append("")
    lines.append("## Files")
    lines.append("")
    lines.append("| File | Tris | Size | W x D x H (m, Blender X/Y/Z) | Children | Slots | Front (Unity) | Source | Preview (Art/Models) |")
    lines.append("|---|---|---|---|---|---|---|---|---|")
    lines += rows
    lines.append("")
    if missing:
        lines.append("## Not produced yet")
        lines.append("")
        lines.append(", ".join("`%s.fbx`" % n for n in missing))
        lines.append("")
    extra = META.get("_notes", [])
    if extra:
        lines.append("## Notes")
        lines.append("")
        for n in extra:
            lines.append("- " + n)
        lines.append("")
    # ---- QA summary from the re-import logs
    lines.append("## Re-import QA")
    lines.append("")
    lines.append("Each FBX is imported into an empty Blender scene by `Tools/blender/verify_fbx.py`. The full per-object results are in "
                 "`Art/Models/_logs/<Name>.verify.json`, and the build-side stats in `<Name>.build.json`. "
                 "\"Open edges\" are expected only on intentionally single-sided sheets (the passport's top pages).")
    lines.append("")
    lines.append("| File | Re-imported | Meshes | UVs on all meshes | Loose geometry | Non-manifold edges | Open edges | Inverted shells | Lowest point (m) | FBX axes |")
    lines.append("|---|---|---|---|---|---|---|---|---|---|")
    for name in ORDER:
        v = load(name, "verify")
        if v is None:
            continue
        meshes = [o for o in v["objects"] if o["type"] == "MESH"]
        uv_ok = all(o.get("uv_layers") for o in meshes)
        loose = sum(o.get("loose_verts", 0) + o.get("loose_edges", 0) for o in meshes)
        nm = sum(o.get("nonmanifold_edges", 0) for o in meshes)
        opn = sum(o.get("boundary_edges", 0) for o in meshes)
        inv = sum(1 for o in meshes if o.get("signed_volume", 0) < 0 and not o.get("boundary_edges"))
        g = v.get("globals", {})
        axes = "Up=Y, Front=+Z, scale 1 m" if (g.get("UpAxis") == 1 and g.get("FrontAxis") == 2 and g.get("FrontAxisSign") == 1
                                               and abs(g.get("UnitScaleFactor", 0) - 100.0) < 1e-6) else str(g)
        lines.append("| `%s.fbx` | yes | %d | %s | %d | %d | %d%s | %d | %.3f | %s |" % (
            name, len(meshes), "yes" if uv_ok else "NO", loose, nm, opn,
            " (pages)" if opn and name == "Passport_Open" else "", inv, v["bbox_min"][2], axes))
    lines.append("")
    lines.append("## Per-asset details")
    lines.append("")
    lines += details
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("wrote", OUT, len(rows), "assets,", len(missing), "missing")


if __name__ == "__main__":
    main()
