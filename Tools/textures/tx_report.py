"""Contact sheet + manifest writer for the generated textures."""
from __future__ import annotations

from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

from tx_graphics import GRAPHICS, flatten_preview
from tx_materials import MATERIALS


def _font(size):
    try:
        return ImageFont.load_default(size=size)
    except TypeError:  # very old Pillow
        return ImageFont.load_default()


def _tiled2(a):
    return np.concatenate([np.concatenate([a, a], 1)] * 2, 0)


def write_contact_sheet(state, tex_dir: Path, art_dir: Path, out: Path):
    W = 1600
    pad = 10
    f_title, f_head, f_lab = _font(26), _font(20), _font(13)
    # ---- materials: [albedo tiled 2x2][normal tiled 2x2]
    P = 180
    cell_w, cell_h = 2 * P + 6, P + 22
    cols = (W - pad) // (cell_w + pad)
    mats = list(MATERIALS)
    rows_m = (len(mats) + cols - 1) // cols
    # ---- graphics
    gfiles = [r for r in state["graphics"].values() if r["fmt"] != "JSON layout"]
    gfiles.sort(key=lambda r: list(GRAPHICS).index(r["group"]) if r["group"] in GRAPHICS else 999)
    G = 176
    gcols = (W - pad) // (G + pad)
    rows_g = (len(gfiles) + gcols - 1) // gcols
    H = 60 + 34 + rows_m * (cell_h + pad) + 44 + rows_g * (G + 22 + pad) + pad
    sheet = Image.new("RGB", (W, H), (34, 35, 38))
    d = ImageDraw.Draw(sheet)
    d.text((pad, 14), "The Twelfth Stamp - procedural texture contact sheet (Tools/textures/gen_textures.py)", fill=(230, 226, 214),
           font=f_title)
    y0 = 60
    d.text((pad, y0), "Tileable materials: albedo tiled 2x2 | normal tiled 2x2 (seams would show as cross lines)",
           fill=(200, 196, 186), font=f_head)
    y0 += 34
    for i, nm in enumerate(mats):
        cx = pad + (i % cols) * (cell_w + pad)
        cy = y0 + (i // cols) * (cell_h + pad)
        a_p, n_p = tex_dir / f"{nm}_a.png", tex_dir / f"{nm}_n.png"
        panels = []
        if a_p.exists():
            panels.append(np.asarray(Image.open(a_p).convert("RGB")))
        if n_p.exists():
            panels.append(np.asarray(Image.open(n_p).convert("RGB")))
        for k, p in enumerate(panels):
            im = Image.fromarray(_tiled2(p)).resize((P, P), Image.LANCZOS)
            sheet.paste(im, (cx + k * (P + 6), cy))
        d.text((cx, cy + P + 4), nm, fill=(214, 210, 200), font=f_lab)
    y0 += rows_m * (cell_h + pad) + 10
    d.text((pad, y0), "Game graphics (RGBA shown over a checkerboard)", fill=(200, 196, 186), font=f_head)
    y0 += 34
    for i, r in enumerate(gfiles):
        cx = pad + (i % gcols) * (G + pad)
        cy = y0 + (i // gcols) * (G + 22 + pad)
        im = Image.fromarray(flatten_preview(np.asarray(Image.open(art_dir / r["file"]))))
        im.thumbnail((G, G), Image.LANCZOS)
        sheet.paste(im, (cx + (G - im.width) // 2, cy + (G - im.height) // 2))
        d.text((cx, cy + G + 3), r["file"].replace(".png", ""), fill=(214, 210, 200), font=f_lab)
    sheet.save(out, optimize=True)
    return out


def _seam_txt(sm):
    return f"{sm['ratio_lr']:.2f} / {sm['ratio_tb']:.2f} {'OK' if sm['ok'] else 'FAIL'}"


def write_manifest(state, out: Path, tex_dir: Path, art_dir: Path):
    L = []
    L.append("# Texture Manifest - The Twelfth Stamp\n")
    L.append("All files below are **original procedural artwork** generated by `Tools/textures/gen_textures.py` "
             "(numpy + Pillow + scipy, fixed seeds derived from each asset name with CRC32). No images were downloaded, "
             "traced or AI-generated, and no texture contains lettering. Regenerate everything with:\n")
    L.append("```\nuv venv Tools/.venv            # once\nuv pip install --python Tools/.venv numpy pillow scipy\n"
             "Tools/.venv/Scripts/python.exe Tools/textures/gen_textures.py\n"
             "Tools/.venv/Scripts/python.exe Tools/textures/gen_textures.py --only stamp_uae paper_ivory   # subset\n```\n")
    L.append("Source modules: `gen_textures.py` (entry point, tiling check, previews), `tx_core.py` (periodic noise, "
             "periodic Voronoi, normals, drawing), `tx_materials.py`, `tx_graphics.py` (pages, cover, acetate, notes, "
             "overlays, UI, icon), `tx_stamps.py`, `tx_paint.py` (portraits, passenger photo, postcards), `tx_report.py`.\n")
    L.append("## Conventions and Unity import settings\n")
    L.append("- `*_a.png`: albedo, 8-bit **sRGB** RGB. Import with *sRGB (Color Texture)* on. Luminance is soft-limited to "
             "roughly 0.13-0.86 (sRGB-encoded 0..1 scale; no pure black/white) so country lighting can do the work.\n"
             "- `*_n.png`: tangent-space normal, **OpenGL / Unity convention (+X right, +Y up = green)**, derived from a "
             "height field with wrap-around Sobel. Import as *Texture Type: Normal map* (do not tick *Create from Grayscale*).\n"
             "- `glass_smudge_a.png`: 8-bit grayscale mask (0 = clean glass, 1 = full smudge). Import with sRGB **off**.\n"
             "- RGBA graphics carry straight (non-premultiplied) alpha; transparent pixels keep the ink/overlay colour so "
             "bilinear filtering does not create dark fringes. Enable *Alpha Is Transparency*.\n"
             "- `passport_cover_ms.png` (optional extra): URP Lit *Metallic Map* layout, R = metallic, A = smoothness. Linear (sRGB off).\n"
             "- Material textures wrap in both axes: set *Wrap Mode: Repeat*.\n")
    L.append("## Tiling check\n")
    L.append("For every tileable file the script compares the wrap-around neighbours (last column vs first column, last row "
             "vs first row) with ordinary neighbouring pixel pairs. Ratio = seam mean-abs-difference / median interior "
             "neighbour difference (8-bit levels). A seamless tile gives ~1.0; a hard seam typically gives 5-50. A file "
             "passes if the seam difference is <= max(1.5 x median, 99th percentile of interior pairs) + 0.5. Ratios "
             "above 1.5 that still pass come from a legitimate feature (joint, ring boundary) that happens to cross the "
             "border, and stay inside the range of interior neighbour pairs. Layout grids are offset so joints avoid the border.\n")
    mats = state["materials"]
    n_ok = sum(1 for r in mats.values() for f in r["files"] if f["seam"]["ok"])
    n_all = sum(len(r["files"]) for r in mats.values())
    worst = max((max(f["seam"]["ratio_lr"], f["seam"]["ratio_tb"]), f["file"]) for r in mats.values() for f in r["files"])
    L.append(f"**Result: {n_ok}/{n_all} tileable files pass** (largest ratio {worst[0]:.2f} on `{worst[1]}`).\n")
    L.append("## A. Tileable materials - `Game/Assets/Resources/Textures/`\n")
    L.append("| File | Size | Purpose | How generated | Seam ratio L-R / T-B | Stats |")
    L.append("|---|---|---|---|---|---|")
    for name in MATERIALS:
        r = mats.get(name)
        if r is None:
            continue
        for f in r["files"]:
            if "lum_mean" in f:
                st = f"lum mean {f['lum_mean']} (p1 {f['lum_p1']}, p99 {f['lum_p99']})"
            elif "tilt_deg" in f:
                st = f"mean normal tilt {f['tilt_deg']} deg"
            else:
                st = f"mask mean {f.get('mask_mean', '')}"
            kind = f["fmt"]
            L.append(f"| `{f['file']}` | {f['w']}x{f['h']} {kind} | {r['purpose']} | {r['method']} | {_seam_txt(f['seam'])} | {st} |")
    L.append("")
    L.append("## B. Game graphics - `Game/Assets/Resources/Art/`\n")
    L.append("| File | Size / format | Purpose | How generated |")
    L.append("|---|---|---|---|")
    for gname in GRAPHICS:
        for r in [v for v in state["graphics"].values() if v["group"] == gname]:
            if r["fmt"] == "JSON layout":
                size = "JSON"
            else:
                size = f"{r['w']}x{r['h']} {r['fmt']}"
                if "transparent_frac" in r:
                    size += f" (alpha {r['alpha_min']}-{r['alpha_max']}, {round(r['transparent_frac'] * 100)}% fully transparent)"
            L.append(f"| `{r['file']}` | {size} | {r['purpose']} | {r['method']} |")
    L.append("")
    L.append("## Notes\n")
    L.append("- `passport_insert_layout.json` lists the 11 seal ovals in the required order (UAE, Egypt, France, USA, Japan, "
             "SaudiArabia, India, Brazil, UnitedKingdom, Morocco, Germany) plus the return field, in Unity UV (origin "
             "bottom-left) and in pixels. `calibration_insert.png` is drawn from the same layout, so its 11 constellation "
             "points sit exactly on the oval centres and the cancelled 12th point on the return-field centre.\n"
             "- `passport_id_layout.json` gives the photo window (4:5, matches `saeed_portrait.png`) for in-engine compositing.\n"
             "- Lens overlays: the centre is exactly transparent inside a circle 84% of the width wide (about 55% of all "
             "pixels), so the central 55% of the view is always clear.\n"
             "- Stamps use ink #7a1f1f; the forged home stamp uses a slightly too-bright red (#a82828), a 3.5 degree tilt, a "
             "shear and a second misregistered impression.\n"
             "- Symbols are original simplified drawings, not national emblems, crests or flags. The portrait is an "
             "original stylised character, not based on any real person.\n"
             "- `Art/texture_contact_sheet.png` shows every material tiled 2x2 and every graphic.\n")
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    return out
